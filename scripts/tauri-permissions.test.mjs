import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
import TOML from "@iarna/toml";
test("Tauri AI grants only explicit admitted-session commands", () => {
  const root = "crates/tauri-plugin-lapis-ai";
  const permissions = TOML.parse(
    readFileSync(`${root}/permissions/default.toml`, "utf8"),
  );
  assert.deepEqual(permissions.default.permissions, []);
  const commands = [
    "targets",
    "list",
    "open",
    "submit",
    "snapshot",
    "attach",
    "detach",
    "ack",
    "close",
  ];
  assert.equal(permissions.set.length, 1);
  assert.equal(permissions.set[0].identifier, "acp-session");
  assert.deepEqual(
    permissions.set[0].permissions.toSorted(),
    commands.map((command) => `allow-${command}`).toSorted(),
  );
  const builder = readFileSync(`${root}/build.rs`, "utf8");
  for (const command of commands) {
    assert(builder.includes(`"${command}"`));
    assert(
      existsSync(`${root}/permissions/autogenerated/commands/${command}.toml`),
    );
  }
});
